-- The free-text sports array becomes rows. Values are matched case-insensitively against the list; anything
-- else stops the migration so it can be fixed by hand rather than guessed. A turf with no sports gets football,
-- the setup form's default.
DO
$$
DECLARE
    unknown text;
BEGIN
    SELECT string_agg(DISTINCT format('%s (venue %s)', s.sport, v.id), ', ') INTO unknown
    FROM venues v, unnest(v.sports) AS s(sport)
    WHERE lower(btrim(s.sport)) NOT IN (SELECT code FROM sports);
    IF unknown IS NOT NULL THEN
        RAISE EXCEPTION 'Unknown sports on turfs: %. Map them to one of the codes in table sports first.', unknown;
    END IF;
END;
$$;

INSERT INTO court_sports (court_id, sport)
