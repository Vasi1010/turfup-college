-- Multi-sport venues: a venue (the place: owner, address, hours, Razorpay account, approval) has courts (what
-- is booked: a football turf, badminton court 2, a shared football/cricket pitch). Bookings, holds, price rules
-- and standing slots move from the turf to the court; regulars, waivers and the monthly refund allowance stay
-- with the venue.
--
-- Every existing turf becomes a venue with the same id and one court ('Main') with that same id too, so old
-- links (/turfs/7) and every stored id keep meaning the same place.
--
-- This is one migration on purpose. PL/pgSQL functions find tables and columns by name only when they run, so
-- the moment turfs is renamed or bookings.turf_id is dropped, release_expired_holds() and count_no_show() break
-- until they are replaced. PostgreSQL runs DDL inside the migration's transaction, so all of this applies
-- together or not at all. V13 then drops the columns that moved from venues to courts.

-- ---------------------------------------------------------------------------
-- turfs -> venues
-- ---------------------------------------------------------------------------
ALTER TABLE turfs RENAME TO venues;
ALTER SEQUENCE turfs_id_seq RENAME TO venues_id_seq;
ALTER INDEX turfs_owner_id_idx RENAME TO venues_owner_id_idx;

-- Constraint names follow the table (turfs_pkey -> venues_pkey, turfs_hours_check -> venues_hours_check, ...).
DO
$$
DECLARE
    c record;
BEGIN
    FOR c IN SELECT conname FROM pg_constraint WHERE conrelid = 'venues'::regclass AND conname LIKE 'turfs\_%'
    LOOP
        EXECUTE format('ALTER TABLE venues RENAME CONSTRAINT %I TO %I', c.conname,
                       'venues' || substr(c.conname, length('turfs') + 1));
    END LOOP;
END;
$$;

