    sort_order               smallint     NOT NULL DEFAULT 0,
    created_at               timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT courts_venue_name_key UNIQUE (venue_id, name),
    CONSTRAINT courts_name_check CHECK (btrim(name) <> ''),
    CONSTRAINT courts_slot_minutes_check CHECK (slot_minutes > 0 AND slot_minutes <= 1440),
    CONSTRAINT courts_advance_amount_check CHECK (advance_amount >= 0),
    CONSTRAINT courts_refund_full_hours_before_check CHECK (refund_full_hours_before >= 0)
);

