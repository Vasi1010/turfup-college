-- A no-show counts against the player at the venue the court belongs to, whichever court it was on.
CREATE OR REPLACE FUNCTION count_no_show() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    INSERT INTO venue_customers (venue_id, player_id, no_show_count)
    SELECT c.venue_id, NEW.player_id, 1 FROM courts c WHERE c.id = NEW.court_id
    ON CONFLICT (venue_id, player_id)
        DO UPDATE SET no_show_count = venue_customers.no_show_count + 1;
    RETURN NULL;
END;
$$;

-- Marks expired HELD bookings as EXPIRED, one court at a time, and returns how many it released.
--
-- Locking: for each court it first takes the court row lock (FOR NO KEY UPDATE), exactly like every booking
-- insert, then updates that court's bookings, then COMMITs before moving on. So it never holds more than one
-- court lock, and blocks bookings on a court only for the moment it takes to expire that court's holds.
--
-- Because it commits per court, call it on its own (autocommit), not inside an open transaction:
--   CALL release_expired_holds();
CREATE OR REPLACE PROCEDURE release_expired_holds(INOUT released integer DEFAULT 0)
    LANGUAGE plpgsql
AS
$$
DECLARE
    grace   integer := (SELECT value::integer FROM app_settings WHERE key = 'grace_minutes');
    court   bigint;
    expired integer;
BEGIN
    released := 0;
    FOR court IN
        SELECT DISTINCT court_id FROM bookings
        WHERE status = 'HELD' AND hold_expires_at < now() -- necessary for expiry; uses bookings_held_expiry_idx
        ORDER BY court_id
    LOOP
        PERFORM 1 FROM courts WHERE id = court FOR NO KEY UPDATE;

        UPDATE bookings SET status = 'EXPIRED'
        WHERE court_id = court
          AND status = 'HELD'
          AND hold_expired(hold_expires_at, payment_started_at, grace);
        GET DIAGNOSTICS expired = ROW_COUNT;
        released := released + expired;

        COMMIT;
    END LOOP;
END;
$$;
