-- TurfUp initial schema.
-- Conventions:
--   * All instants are timestamptz; IST conversion happens at the application edges.
--   * All money columns are bigint paise (₹1 = 100 paise). Never floating point.
--   * day_of_week is ISO: 1 = Monday ... 7 = Sunday (matches java.time.DayOfWeek).
--   * Operating day: times of day are minutes from the start of the turf's operating day (IST
--     midnight) and may run past 1440, up to 2880. A turf open 6 AM to 2 AM is 360..1560, and
--     Saturday 11 PM-1 AM is 1380..1500 on Saturday's operating day (priced as Saturday).
--     day_of_week always refers to the operating day.
--   * Enumerations are varchar + CHECK so new values only need a new migration.

CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(120) NOT NULL,
    phone         varchar(20)  NOT NULL,
    email         varchar(255),
    password_hash varchar(255) NOT NULL,
    role          varchar(10)  NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT users_phone_key UNIQUE (phone),
    CONSTRAINT users_role_check CHECK (role IN ('PLAYER', 'OWNER', 'ADMIN'))
);

-- ---------------------------------------------------------------------------
-- turfs
-- Opening hours in operating-day minutes: opens on the calendar day (0..1439),
-- may close past midnight (close_minute > 1440), open at most 24 hours.
-- ---------------------------------------------------------------------------
CREATE TABLE turfs (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       bigint        NOT NULL REFERENCES users (id),
    name           varchar(120)  NOT NULL,
    area           varchar(120)  NOT NULL,
    address        text          NOT NULL,
    lat            numeric(9, 6),
    lng            numeric(9, 6),
    sports         text[]        NOT NULL DEFAULT '{}',
    open_minute    smallint      NOT NULL,
    close_minute   smallint      NOT NULL,
    slot_minutes   integer       NOT NULL DEFAULT 60,
    advance_amount bigint        NOT NULL DEFAULT 20000,
    refund_policy  text,
    active         boolean       NOT NULL DEFAULT true,
    CONSTRAINT turfs_open_minute_check CHECK (open_minute BETWEEN 0 AND 1439),
    CONSTRAINT turfs_close_minute_check CHECK (close_minute BETWEEN 1 AND 2880),
    CONSTRAINT turfs_hours_check CHECK (close_minute > open_minute AND close_minute - open_minute <= 1440),
    CONSTRAINT turfs_slot_minutes_check CHECK (slot_minutes > 0 AND slot_minutes <= 1440),
    CONSTRAINT turfs_advance_amount_check CHECK (advance_amount >= 0),
    CONSTRAINT turfs_lat_check CHECK (lat BETWEEN -90 AND 90),
    CONSTRAINT turfs_lng_check CHECK (lng BETWEEN -180 AND 180)
);

CREATE INDEX turfs_owner_id_idx ON turfs (owner_id);

COMMENT ON COLUMN turfs.advance_amount IS 'paise';

-- ---------------------------------------------------------------------------
-- price_rules
-- Times are operating-day minutes (0..2880), so a rule can end at 24:00 or
-- cover the hours after midnight that belong to the previous operating day.
-- day_of_week NULL = general rule; a day-specific rule overrides it.
-- Rules of the same specificity on the same turf may not overlap: two general
-- rules (COALESCE -> 0) conflict, two rules for the same day conflict, but a
-- day-specific rule may overlap a general one.
-- ---------------------------------------------------------------------------
CREATE TABLE price_rules (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turf_id      bigint   NOT NULL REFERENCES turfs (id),
    day_of_week  smallint,
    start_minute smallint NOT NULL,
    end_minute   smallint NOT NULL,
    rate         bigint   NOT NULL,
    CONSTRAINT price_rules_day_of_week_check CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT price_rules_start_minute_check CHECK (start_minute BETWEEN 0 AND 2880),
    CONSTRAINT price_rules_end_minute_check CHECK (end_minute BETWEEN 0 AND 2880),
    CONSTRAINT price_rules_range_check CHECK (end_minute > start_minute),
    CONSTRAINT price_rules_rate_check CHECK (rate >= 0),
    CONSTRAINT price_rules_no_overlap EXCLUDE USING gist (
        turf_id WITH =,
        (COALESCE(day_of_week, 0)) WITH =,
        int4range(start_minute, end_minute) WITH &&
    )
);

COMMENT ON COLUMN price_rules.rate IS 'paise per hour';

-- ---------------------------------------------------------------------------
-- recurring_bookings
-- Operating-day minutes; e.g. every Saturday 11 PM-1 AM is
-- day_of_week = 6, start_minute = 1380, end_minute = 1500.
-- ---------------------------------------------------------------------------
CREATE TABLE recurring_bookings (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turf_id      bigint   NOT NULL REFERENCES turfs (id),
    player_id    bigint   NOT NULL REFERENCES users (id),
    day_of_week  smallint NOT NULL,
    start_minute smallint NOT NULL,
    end_minute   smallint NOT NULL,
    valid_from   date     NOT NULL,
    valid_to     date,
    CONSTRAINT recurring_bookings_day_of_week_check CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT recurring_bookings_start_minute_check CHECK (start_minute BETWEEN 0 AND 2880),
    CONSTRAINT recurring_bookings_end_minute_check CHECK (end_minute BETWEEN 0 AND 2880),
    CONSTRAINT recurring_bookings_range_check CHECK (end_minute > start_minute),
    CONSTRAINT recurring_bookings_validity_check CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX recurring_bookings_turf_id_idx ON recurring_bookings (turf_id);

-- ---------------------------------------------------------------------------
-- bookings
-- ---------------------------------------------------------------------------
CREATE TABLE bookings (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turf_id            bigint       NOT NULL REFERENCES turfs (id),
    player_id          bigint       REFERENCES users (id),
    walkin_name        varchar(120),
    walkin_phone       varchar(20),
    start_at           timestamptz  NOT NULL,
    end_at             timestamptz  NOT NULL,
    status             varchar(12)  NOT NULL,
    source             varchar(10)  NOT NULL,
    total_price        bigint       NOT NULL,
    advance_required   bigint       NOT NULL,
    hold_expires_at    timestamptz,
    payment_started_at timestamptz,
    recurring_id       bigint       REFERENCES recurring_bookings (id),
    created_at         timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT bookings_status_check
        CHECK (status IN ('HELD', 'CONFIRMED', 'COMPLETED', 'EXPIRED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT bookings_source_check CHECK (source IN ('ONLINE', 'WALKIN', 'PHONE')),
    CONSTRAINT bookings_time_range_check CHECK (end_at > start_at),
    CONSTRAINT bookings_total_price_check CHECK (total_price >= 0),
    CONSTRAINT bookings_advance_required_check CHECK (advance_required >= 0),
    CONSTRAINT bookings_held_has_expiry_check CHECK (status <> 'HELD' OR hold_expires_at IS NOT NULL),
    -- Online bookings belong to a player; owner-entered ones need a player or a walk-in name.
    CONSTRAINT bookings_customer_check CHECK (
        (source = 'ONLINE' AND player_id IS NOT NULL)
        OR (source IN ('WALKIN', 'PHONE') AND (player_id IS NOT NULL OR walkin_name IS NOT NULL))
    ),
    -- No double booking: active bookings on the same turf may not overlap.
    -- tstzrange is half-open [start, end), so back-to-back slots are allowed.
    CONSTRAINT bookings_no_overlap EXCLUDE USING gist (
        turf_id WITH =,
        tstzrange(start_at, end_at) WITH &&
    ) WHERE (status IN ('HELD', 'CONFIRMED'))
);

-- One active hold per player at a time.
CREATE UNIQUE INDEX bookings_one_active_hold_per_player
    ON bookings (player_id)
    WHERE status = 'HELD';

CREATE INDEX bookings_player_id_idx ON bookings (player_id);
CREATE INDEX bookings_held_expiry_idx ON bookings (hold_expires_at) WHERE status = 'HELD';

COMMENT ON COLUMN bookings.total_price IS 'paise; computed at booking time and never recomputed';
COMMENT ON COLUMN bookings.advance_required IS 'paise; 0 when the advance is waived';
COMMENT ON COLUMN bookings.payment_started_at IS
    'set when a payment attempt starts; a HELD row stays active until hold_expires_at + grace_minutes';

-- ---------------------------------------------------------------------------
-- payments
-- ---------------------------------------------------------------------------
CREATE TABLE payments (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id         bigint       NOT NULL REFERENCES bookings (id),
    kind               varchar(10)  NOT NULL,
    amount             bigint       NOT NULL,
    method             varchar(12)  NOT NULL,
    status             varchar(10)  NOT NULL,
    gateway_order_id   varchar(64),
    gateway_payment_id varchar(64),
    created_at         timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT payments_kind_check CHECK (kind IN ('ADVANCE', 'BALANCE', 'REFUND')),
    CONSTRAINT payments_amount_check CHECK (amount > 0),
    CONSTRAINT payments_method_check CHECK (method IN ('SIMULATED', 'RAZORPAY', 'CASH', 'UPI')),
    CONSTRAINT payments_status_check CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    -- Webhook idempotency: a gateway payment can be recorded only once.
    CONSTRAINT payments_gateway_payment_id_key UNIQUE (gateway_payment_id)
);

CREATE INDEX payments_booking_id_idx ON payments (booking_id);

COMMENT ON COLUMN payments.amount IS 'paise';

-- ---------------------------------------------------------------------------
-- turf_customers (regulars, per turf)
-- ---------------------------------------------------------------------------
CREATE TABLE turf_customers (
    turf_id        bigint  NOT NULL REFERENCES turfs (id),
    player_id      bigint  NOT NULL REFERENCES users (id),
    advance_waived boolean NOT NULL DEFAULT false,
    no_show_count  integer NOT NULL DEFAULT 0,
    notes          text,
    PRIMARY KEY (turf_id, player_id),
    CONSTRAINT turf_customers_no_show_count_check CHECK (no_show_count >= 0)
);

CREATE INDEX turf_customers_player_id_idx ON turf_customers (player_id);

-- ---------------------------------------------------------------------------
-- app_settings
-- ---------------------------------------------------------------------------
CREATE TABLE app_settings (
    key   varchar(64) PRIMARY KEY,
    value text        NOT NULL
);

INSERT INTO app_settings (key, value) VALUES
    ('hold_minutes', '5'),
    ('grace_minutes', '2'),
    ('min_pay_seconds_remaining', '30');

-- ---------------------------------------------------------------------------
-- subscriptions (business version only; unused while turfup.subscriptions.enabled = false)
-- ---------------------------------------------------------------------------
CREATE TABLE subscriptions (
    turf_id       bigint      PRIMARY KEY REFERENCES turfs (id),
    plan          varchar(32) NOT NULL,
    status        varchar(10) NOT NULL,
    trial_ends_at timestamptz,
    paid_until    timestamptz,
    CONSTRAINT subscriptions_status_check CHECK (status IN ('TRIAL', 'ACTIVE', 'PAST_DUE', 'CANCELLED'))
);
