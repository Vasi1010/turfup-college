-- Cricket tournaments with ball-by-ball scoring (task B1). The design and its decisions: docs/tournament.md.
--
-- The one rule of this schema: a ball is a row in `deliveries`, and every number shown anywhere (scores, overs,
-- batting and bowling figures, the points table, leaderboards) is computed from those rows. Nothing stores a total, so
-- the numbers always add up, and undoing a ball (marking its row deleted) undoes everything that followed from it.
-- Over and ball numbers are not stored either: they follow from `seq` and `is_legal` (see innings_totals below).
--
-- Tournament players are `cricketers`, not app users: most will never have an account, and "player" already means a
-- registered user (users.role = 'PLAYER', bookings.player_id).

-- ---------------------------------------------------------------------------
-- tournaments: one event, with the organiser's rules
-- ---------------------------------------------------------------------------
CREATE TABLE tournaments (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 varchar(120) NOT NULL,
    venue_name           varchar(120) NOT NULL,
    venue_id             bigint REFERENCES venues (id),        -- optional link to a TurfUp venue (later)
    start_date           date         NOT NULL,
    end_date             date         NOT NULL,
    status               varchar(10)  NOT NULL DEFAULT 'UPCOMING',
    overs_per_innings    smallint     NOT NULL,
    max_overs_per_bowler smallint,                              -- null: no limit
    balls_per_over       smallint     NOT NULL DEFAULT 6,
    players_per_side     smallint     NOT NULL DEFAULT 11,      -- all out at players_per_side - 1 wickets
    wide_runs            smallint     NOT NULL DEFAULT 1,       -- penalty runs for a wide
    no_ball_runs         smallint     NOT NULL DEFAULT 1,       -- penalty runs for a no-ball
    points_win           smallint     NOT NULL DEFAULT 2,
    points_tie           smallint     NOT NULL DEFAULT 1,
    points_no_result     smallint     NOT NULL DEFAULT 1,
    tiebreaker           varchar(12)  NOT NULL DEFAULT 'NRR',
    local_rules          jsonb        NOT NULL DEFAULT '{}',    -- e.g. {"noLbw": true, "freeHit": true, "lastManStands": false}
    created_by           bigint       NOT NULL REFERENCES users (id),
    created_at           timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT tournaments_name_check CHECK (btrim(name) <> ''),
    CONSTRAINT tournaments_dates_check CHECK (end_date >= start_date),
    CONSTRAINT tournaments_status_check CHECK (status IN ('UPCOMING', 'LIVE', 'DONE')),
    CONSTRAINT tournaments_overs_check CHECK (overs_per_innings BETWEEN 1 AND 50),
    CONSTRAINT tournaments_bowler_overs_check
        CHECK (max_overs_per_bowler IS NULL OR max_overs_per_bowler BETWEEN 1 AND overs_per_innings),
    CONSTRAINT tournaments_balls_per_over_check CHECK (balls_per_over BETWEEN 4 AND 8),
    CONSTRAINT tournaments_players_per_side_check CHECK (players_per_side BETWEEN 2 AND 11),
    CONSTRAINT tournaments_extra_runs_check CHECK (wide_runs BETWEEN 0 AND 2 AND no_ball_runs BETWEEN 0 AND 2),
    CONSTRAINT tournaments_points_check CHECK (points_win > points_tie AND points_tie >= 0 AND points_no_result >= 0),
    CONSTRAINT tournaments_tiebreaker_check CHECK (tiebreaker IN ('NRR', 'HEAD_TO_HEAD')),
    CONSTRAINT tournaments_local_rules_check CHECK (jsonb_typeof(local_rules) = 'object')
);

-- ---------------------------------------------------------------------------
-- teams, cricketers and squads
-- ---------------------------------------------------------------------------
CREATE TABLE teams (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id bigint      NOT NULL REFERENCES tournaments (id),
    name          varchar(60) NOT NULL,
    short_name    varchar(5)  NOT NULL,
    group_name    varchar(20),                                  -- 'A', 'B'; null when there are no groups
    captain_id    bigint,                                       -- must be in the squad (FK below)
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT teams_tournament_name_key UNIQUE (tournament_id, name),
    CONSTRAINT teams_tournament_short_name_key UNIQUE (tournament_id, short_name),
    CONSTRAINT teams_id_tournament_key UNIQUE (id, tournament_id), -- target of the composite FKs below
    CONSTRAINT teams_name_check CHECK (btrim(name) <> ''),
    CONSTRAINT teams_short_name_check CHECK (short_name ~ '^[A-Z0-9]{2,5}$')
);

CREATE TABLE cricketers (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(120) NOT NULL,
    phone      varchar(20),
    created_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT cricketers_name_check CHECK (btrim(name) <> '')
);

-- A cricketer plays for one team per tournament: the composite FK pins the team to the tournament, and the unique
-- key on (tournament_id, cricketer_id) does the rest.
CREATE TABLE squad_members (
    team_id       bigint      NOT NULL,
    tournament_id bigint      NOT NULL,
    cricketer_id  bigint      NOT NULL REFERENCES cricketers (id),
    jersey_no     smallint,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (team_id, cricketer_id),
    CONSTRAINT squad_members_team_fkey FOREIGN KEY (team_id, tournament_id) REFERENCES teams (id, tournament_id),
    CONSTRAINT squad_members_one_team_key UNIQUE (tournament_id, cricketer_id),
    CONSTRAINT squad_members_jersey_no_check CHECK (jersey_no BETWEEN 0 AND 999)
);

CREATE UNIQUE INDEX squad_members_jersey_no_key ON squad_members (team_id, jersey_no) WHERE jersey_no IS NOT NULL;

ALTER TABLE teams ADD CONSTRAINT teams_captain_fkey
    FOREIGN KEY (id, captain_id) REFERENCES squad_members (team_id, cricketer_id);

-- ---------------------------------------------------------------------------
-- matches
-- A knockout fixture can exist before its teams are known: team_a_label ("Winner SF 1") stands in until then.
-- ---------------------------------------------------------------------------
CREATE TABLE matches (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id     bigint       NOT NULL REFERENCES tournaments (id),
    match_no          smallint     NOT NULL,
    stage             varchar(13)  NOT NULL DEFAULT 'GROUP',
    team_a_id         bigint,
    team_b_id         bigint,
    team_a_label      varchar(40),
    team_b_label      varchar(40),
    scheduled_at      timestamptz,
    overs_per_innings smallint,                                 -- null: the tournament's; set for a shortened match
    status            varchar(10)  NOT NULL DEFAULT 'UPCOMING',
    toss_winner_id    bigint REFERENCES teams (id),
    toss_decision     varchar(4),
    result            varchar(9),                               -- set when the match is DONE or ABANDONED
    winner_id         bigint REFERENCES teams (id),             -- WIN; or a TIE decided by a super over
    result_note       varchar(120),                             -- shown with the result, e.g. "Won the super over"
    scorer_user_id    bigint REFERENCES users (id),             -- who may score this match
    version           integer      NOT NULL DEFAULT 0,          -- +1 on every scoring change; pages poll for it
    created_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT matches_tournament_match_no_key UNIQUE (tournament_id, match_no),
    CONSTRAINT matches_team_a_fkey FOREIGN KEY (team_a_id, tournament_id) REFERENCES teams (id, tournament_id),
    CONSTRAINT matches_team_b_fkey FOREIGN KEY (team_b_id, tournament_id) REFERENCES teams (id, tournament_id),
    CONSTRAINT matches_stage_check CHECK (stage IN ('GROUP', 'QUARTER_FINAL', 'SEMI_FINAL', 'FINAL')),
    CONSTRAINT matches_status_check CHECK (status IN ('UPCOMING', 'LIVE', 'DONE', 'ABANDONED')),
    CONSTRAINT matches_teams_check CHECK (team_a_id <> team_b_id),
    CONSTRAINT matches_team_a_check CHECK (team_a_id IS NOT NULL OR btrim(team_a_label) <> ''),
    CONSTRAINT matches_team_b_check CHECK (team_b_id IS NOT NULL OR btrim(team_b_label) <> ''),
    CONSTRAINT matches_started_check CHECK (status = 'UPCOMING' OR (team_a_id IS NOT NULL AND team_b_id IS NOT NULL)),
    CONSTRAINT matches_overs_check CHECK (overs_per_innings BETWEEN 1 AND 50),
    CONSTRAINT matches_toss_check CHECK ((toss_winner_id IS NULL) = (toss_decision IS NULL)),
    CONSTRAINT matches_toss_winner_check CHECK (toss_winner_id IN (team_a_id, team_b_id)),
    CONSTRAINT matches_toss_decision_check CHECK (toss_decision IN ('BAT', 'BOWL')),
    CONSTRAINT matches_result_check CHECK (result IN ('WIN', 'TIE', 'NO_RESULT')),
    CONSTRAINT matches_result_status_check CHECK ((result IS NOT NULL) = (status IN ('DONE', 'ABANDONED'))),
    CONSTRAINT matches_abandoned_check CHECK (status <> 'ABANDONED' OR result = 'NO_RESULT'),
    CONSTRAINT matches_win_check CHECK (result <> 'WIN' OR winner_id IS NOT NULL),
    CONSTRAINT matches_winner_check CHECK (winner_id IS NULL OR (result IN ('WIN', 'TIE')
                                                                AND winner_id IN (team_a_id, team_b_id)))
);

CREATE INDEX matches_tournament_id_idx ON matches (tournament_id);

-- ---------------------------------------------------------------------------
-- innings
-- The target is not stored: it is the first innings' runs + 1. The openers and the opening bowler are, because the
-- live page shows them before the first ball (after it, every ball names its batters and bowler).
-- ---------------------------------------------------------------------------
CREATE TABLE innings (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id               bigint      NOT NULL REFERENCES matches (id),
    number                 smallint    NOT NULL,
    batting_team_id        bigint      NOT NULL REFERENCES teams (id),
    bowling_team_id        bigint      NOT NULL REFERENCES teams (id),
    opening_striker_id     bigint      NOT NULL REFERENCES cricketers (id),
    opening_non_striker_id bigint      NOT NULL REFERENCES cricketers (id),
    opening_bowler_id      bigint      NOT NULL REFERENCES cricketers (id),
    status                 varchar(4)  NOT NULL DEFAULT 'LIVE',
    end_reason             varchar(7),                          -- why it ended; null while LIVE
    started_at             timestamptz NOT NULL DEFAULT now(),
    ended_at               timestamptz,
    CONSTRAINT innings_match_number_key UNIQUE (match_id, number),
    CONSTRAINT innings_number_check CHECK (number IN (1, 2)),
    CONSTRAINT innings_teams_check CHECK (batting_team_id <> bowling_team_id),
    CONSTRAINT innings_openers_check CHECK (opening_striker_id <> opening_non_striker_id),
    CONSTRAINT innings_opening_bowler_check
        CHECK (opening_bowler_id NOT IN (opening_striker_id, opening_non_striker_id)),
    CONSTRAINT innings_status_check CHECK (status IN ('LIVE', 'DONE')),
    CONSTRAINT innings_end_reason_check CHECK (end_reason IN ('OVERS', 'ALL_OUT', 'TARGET', 'CLOSED')),
    CONSTRAINT innings_ended_check CHECK ((status = 'DONE') = (end_reason IS NOT NULL AND ended_at IS NOT NULL))
);

-- At most one innings of a match is being played.
CREATE UNIQUE INDEX innings_one_live_key ON innings (match_id) WHERE status = 'LIVE';

-- ---------------------------------------------------------------------------
-- deliveries: one row per ball, the only source of every number
-- ---------------------------------------------------------------------------
CREATE TABLE deliveries (
    id             uuid        PRIMARY KEY,                     -- made by the scorer's phone: a retried upload is a no-op
    innings_id     bigint      NOT NULL REFERENCES innings (id),
    seq            integer     NOT NULL,                        -- 1, 2, 3 ... within the innings, wides included
    striker_id     bigint      NOT NULL REFERENCES cricketers (id),
    non_striker_id bigint      NOT NULL REFERENCES cricketers (id),
    bowler_id      bigint      NOT NULL REFERENCES cricketers (id),
    runs_bat       smallint    NOT NULL DEFAULT 0,              -- off the bat, also on a no-ball
    extra_type     varchar(2),                                  -- WD, NB, B (bye), LB (leg bye)
    extra_runs     smallint    NOT NULL DEFAULT 0,              -- all extras on the ball, penalty included: wide + 4 byes = 5
    is_legal       boolean     GENERATED ALWAYS AS (extra_type IS NULL OR extra_type IN ('B', 'LB')) STORED,
    wicket_type    varchar(12),
    player_out_id  bigint      REFERENCES cricketers (id),
    fielder_id     bigint      REFERENCES cricketers (id),
    deleted_at     timestamptz,                                 -- undo
    created_by     bigint      NOT NULL REFERENCES users (id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT deliveries_seq_check CHECK (seq >= 1),
    CONSTRAINT deliveries_runs_bat_check CHECK (runs_bat BETWEEN 0 AND 7),
    CONSTRAINT deliveries_extra_type_check CHECK (extra_type IN ('WD', 'NB', 'B', 'LB')),
    CONSTRAINT deliveries_extra_runs_check CHECK (extra_runs BETWEEN 0 AND 9 AND (extra_type IS NOT NULL OR extra_runs = 0)),
    CONSTRAINT deliveries_no_bat_runs_check CHECK (extra_type IS NULL OR extra_type = 'NB' OR runs_bat = 0),
    CONSTRAINT deliveries_batters_check CHECK (striker_id <> non_striker_id),
    CONSTRAINT deliveries_bowler_check CHECK (bowler_id NOT IN (striker_id, non_striker_id)),
    CONSTRAINT deliveries_wicket_type_check CHECK (wicket_type IN ('BOWLED', 'CAUGHT', 'LBW', 'RUN_OUT', 'STUMPED',
                                                                   'HIT_WICKET', 'RETIRED_OUT', 'RETIRED_HURT')),
    CONSTRAINT deliveries_wicket_check CHECK ((wicket_type IS NULL) = (player_out_id IS NULL)),
    CONSTRAINT deliveries_player_out_check CHECK (player_out_id IN (striker_id, non_striker_id)),
    -- The non-striker can only be run out or retire.
    CONSTRAINT deliveries_non_striker_out_check
        CHECK (player_out_id <> non_striker_id OR wicket_type IN ('RUN_OUT', 'RETIRED_OUT', 'RETIRED_HURT')),
    -- Off a no-ball only a run out (or retiring); off a wide also stumped or hit wicket.
    CONSTRAINT deliveries_no_ball_wicket_check
        CHECK (extra_type IS DISTINCT FROM 'NB' OR wicket_type IN ('RUN_OUT', 'RETIRED_OUT', 'RETIRED_HURT')),
    CONSTRAINT deliveries_wide_wicket_check
        CHECK (extra_type IS DISTINCT FROM 'WD'
               OR wicket_type IN ('RUN_OUT', 'STUMPED', 'HIT_WICKET', 'RETIRED_OUT', 'RETIRED_HURT')),
    CONSTRAINT deliveries_fielder_check CHECK (fielder_id IS NULL OR wicket_type IN ('CAUGHT', 'RUN_OUT', 'STUMPED'))
);

-- The innings' balls in order. An undone ball keeps its seq, and the next ball reuses it.
CREATE UNIQUE INDEX deliveries_innings_seq_key ON deliveries (innings_id, seq) WHERE deleted_at IS NULL;

COMMENT ON COLUMN deliveries.extra_runs IS 'every extra on this ball, penalty included: a wide with 4 byes is 5';

-- ---------------------------------------------------------------------------
-- innings_totals: the score of every innings, computed from its balls (the pattern every figure follows)
-- RETIRED_HURT is not a wicket. overs = legal_balls / balls_per_over, shown as "7.3".
-- ---------------------------------------------------------------------------
CREATE VIEW innings_totals AS
SELECT i.id                                                                   AS innings_id,
       COALESCE(sum(d.runs_bat + d.extra_runs), 0)                            AS runs,
       count(*) FILTER (WHERE d.wicket_type IS NOT NULL AND d.wicket_type <> 'RETIRED_HURT') AS wickets,
       count(*) FILTER (WHERE d.is_legal)                                     AS legal_balls,
       COALESCE(sum(d.extra_runs), 0)                                         AS extras
FROM innings i
LEFT JOIN deliveries d ON d.innings_id = i.id AND d.deleted_at IS NULL
GROUP BY i.id;
